#!/usr/bin/env python3
"""Author exact exp2/TPT coefficients for linear interpolation at audio rate."""
import math
from pathlib import Path
root=Path(__file__).resolve().parents[2]
lines=['/* Generated by tools/dsp/prophet_tables.py. Math constants only. */']
for name,values in [('p5Exp',[2**(i/2048) for i in range(2049)]),('p5Ota',[(lambda x:x*(27+x*x)/(27+9*x*x))(3*i/2048) for i in range(2049)]),('p5G',[(lambda g:g/(1+g))(math.tan(math.pi*.2*i/2048)) for i in range(2049)])]:
 lines.append('static const float %s[2049] = {'%name)
 for i in range(0,len(values),8):lines.append(' '+','.join(('%.10ef'%x) for x in values[i:i+8])+',')
 lines.append('};')
(root/'core/synth/prophet_tables.inc').write_text('\n'.join(lines)+'\n')
